func shouldSuppressTransientTextRestore(
    isAwaitingTransientResolution: Bool,
    baseline: ClipboardTextFingerprint?,
    current: ClipboardTextFingerprint?
) -> Bool {
    guard isAwaitingTransientResolution, let baseline else { return false }
    return current == baseline
}

func shouldTrackTransientPasteboardChange(
    previousChangeCount: Int?,
    currentChangeCount: Int,
    containsTransientMarker: Bool
) -> Bool {
    guard !containsTransientMarker else { return true }
    guard let previousChangeCount, currentChangeCount > previousChangeCount else { return false }
    return currentChangeCount - previousChangeCount > 1
}

@MainActor
enum ClipboardPayloadClassifier {
    static let maximumTextBytes = 1 * 1_024 * 1_024
    static let maximumImageBytes = ClipboardImageDecoder.maximumSourceBytes
    static let maximumFileItems = 10_000
    static let maximumFileURLReadBytes = 8 * 1_024 * 1_024
    static let maximumFileURLReadCount = 512
    static let maximumTypeEntries = 64
    static let maximumMarkerTypeEntries = 1_024
    static let maximumPreviewCharacters = 1_000
    static let maximumPreviewScalarsPerCharacter = 16
    static let maximumPreviewUnicodeScalars = 1_000
    static let maximumFingerprintSourceBytes = ClipboardImageDecoder.maximumSourceBytes
    static let suppressedToastTypes: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    ]

    static func shouldSuppressToast(items: [NSPasteboardItem]) -> Bool {
        var remainingTypeEntries = maximumMarkerTypeEntries
        for item in items.prefix(maximumFileItems) {
            let types = item.types
            for type in types.prefix(remainingTypeEntries) {
                guard !suppressedToastTypes.contains(type) else { return true }
            }
            remainingTypeEntries -= min(types.count, remainingTypeEntries)
            guard remainingTypeEntries > 0 else { return false }
        }
        return false
    }

    static func textFingerprint(
        items: [NSPasteboardItem],
        payloadReader: any PasteboardPayloadReading = SystemPasteboardPayloadReader()
    ) async -> ClipboardTextFingerprint? {
        let result = await readTextPayload(
            in: boundedTypes(in: items),
            payloadReader: payloadReader
        )
        return await textFingerprint(from: result)
    }

    static func analyze(
        items: [NSPasteboardItem],
        generation: UInt64,
        totalItemCount: Int? = nil,
        fileURLReader: any PasteboardFileURLReading = SystemPasteboardFileURLReader(),
        payloadReader: any PasteboardPayloadReading = SystemPasteboardPayloadReader(),
        tokenizer: ClipboardTokenizer? = nil,
        screenshotDynamicRange: ClipboardScreenshotDynamicRange? = nil
    ) async -> ClipboardPayloadAnalysis {
        let boundedItems = Array(items.prefix(maximumFileItems))
        let types = boundedTypes(in: boundedItems)
        let textPayload = await readTextPayload(in: types, payloadReader: payloadReader)
        guard !Task.isCancelled else { return cancelledAnalysis(generation: generation) }
        let fingerprint = await textFingerprint(from: textPayload)
        guard !Task.isCancelled else { return cancelledAnalysis(generation: generation) }

        let classification: ClipboardPayloadClassification
        let textMetrics: ClipboardTextMetrics?
        if let files = await classifyFiles(
            in: boundedItems,
            generation: generation,
            totalItemCount: totalItemCount,
            fileURLReader: fileURLReader
        ) {
            classification = files
            textMetrics = nil
            guard !Task.isCancelled else { return cancelledAnalysis(generation: generation) }
        } else {
            guard !Task.isCancelled else { return cancelledAnalysis(generation: generation) }
            if let image = await classifyImage(
                types: types,
                generation: generation,
                payloadReader: payloadReader,
                screenshotDynamicRange: screenshotDynamicRange
            ) {
                guard !Task.isCancelled else { return cancelledAnalysis(generation: generation) }
                classification = image
                textMetrics = nil
            } else {
                guard !Task.isCancelled else { return cancelledAnalysis(generation: generation) }
                if let textPayload {
                    let textResult = await classifyText(
                        materializedText: textPayload,
                        generation: generation,
                        tokenizer: tokenizer
                    )
                    classification = textResult.classification
                    textMetrics = textResult.metrics
                } else {
                    classification = classifyGeneric(types: types, generation: generation)
                    textMetrics = nil
                }
            }
        }
        guard !Task.isCancelled else { return cancelledAnalysis(generation: generation) }

        return ClipboardPayloadAnalysis(
            classification: classification,
            textFingerprint: fingerprint,
            textMetrics: textMetrics
        )
    }

    static func shouldEnrichImage(byteCount: Int) -> Bool {
        byteCount <= maximumImageBytes
    }

    static func normalizedPreview(_ text: String) -> String {
        var normalized = ""
        var needsSpace = false
        var truncated = false
        var unicodeScalarCount = 0

        for character in text {
            if character.isWhitespace {
                needsSpace = !normalized.isEmpty
            } else {
                let characterScalarCount = character.unicodeScalars.count
                let separatorScalarCount = needsSpace ? 1 : 0
                guard characterScalarCount <= maximumPreviewScalarsPerCharacter,
                      unicodeScalarCount + separatorScalarCount + characterScalarCount
                        <= maximumPreviewUnicodeScalars
                else {
                    truncated = true
                    break
                }
                if needsSpace {
                    normalized.append(" ")
                    needsSpace = false
                    unicodeScalarCount += 1
                }
                normalized.append(character)
                unicodeScalarCount += characterScalarCount
            }
        }

        let bounded = normalized.prefix(maximumPreviewCharacters + 1)
        guard truncated || bounded.count > maximumPreviewCharacters else { return String(bounded) }
        guard !bounded.isEmpty else { return "" }
        return String(bounded.prefix(maximumPreviewCharacters)) + "…"
    }

}

extension ClipboardPayloadClassifier {
    private static func classifyFiles(
        in items: [NSPasteboardItem],
        generation: UInt64,
        totalItemCount: Int?,
        fileURLReader: any PasteboardFileURLReading
    ) async -> ClipboardPayloadClassification? {
        await scanFiles(
            in: items,
            generation: generation,
            totalItemCount: totalItemCount,
            fileURLReader: fileURLReader
        )
    }

    private static func unavailableClassification(
        generation: UInt64
    ) -> ClipboardPayloadClassification {
        return .unavailable(generation: generation)
    }

    private static func cancelledAnalysis(generation: UInt64) -> ClipboardPayloadAnalysis {
        ClipboardPayloadAnalysis(
            classification: unavailableClassification(generation: generation),
            textFingerprint: nil,
            textMetrics: nil
        )
    }

    private static func classifyImage(
        types: [(NSPasteboardItem, NSPasteboard.PasteboardType)],
        generation: UInt64,
        payloadReader: any PasteboardPayloadReading,
        screenshotDynamicRange: ClipboardScreenshotDynamicRange?
    ) async -> ClipboardPayloadClassification? {
        let preferredTypes: [NSPasteboard.PasteboardType] = [.png, .tiff]
        let match = preferredTypes.lazy.compactMap { preferred in
            types.first(where: { _, type in type == preferred })
        }.first ?? types.first(where: { _, type in
            PasteboardTypePolicy.isImage(type)
        })

        guard let (item, type) = match else { return nil }
        let data: Data?
        let byteCount: Int?
        switch await payloadReader.readData(
            from: item,
            forType: type,
            maximumBytes: maximumImageBytes
        ) {
        case .missing:
            data = nil
            byteCount = nil
        case let .data(value):
            data = value
            byteCount = value.count
        case let .tooLarge(value):
            data = nil
            byteCount = value
        case .timedOut, .failed, .unavailable:
            return unavailableClassification(generation: generation)
        case .cancelled:
            return Task.isCancelled
                ? nil
                : unavailableClassification(generation: generation)
        }
        let request = data.map {
            ClipboardImageEnrichmentRequest(
                generation: generation,
                data: $0,
                typeIdentifier: type.rawValue
            )
        }
        return .image(
            generation: generation,
            byteCount: byteCount,
            imageEnrichment: request,
            screenshotDynamicRange: screenshotDynamicRange
        )
    }

    private static func classifyText(
        materializedText: MaterializedText,
        generation: UInt64,
        tokenizer: ClipboardTokenizer?
    ) async -> (
        classification: ClipboardPayloadClassification,
        metrics: ClipboardTextMetrics?
    ) {
        let preview: String?
        let oversizedByteCount: Int?
        let metrics: ClipboardTextMetrics?
        switch materializedText.result {
        case .missing:
            preview = nil
            oversizedByteCount = nil
            metrics = nil
        case let .tooLarge(byteCount):
            preview = nil
            oversizedByteCount = byteCount
            metrics = nil
        case let .data(data):
            if data.count > maximumTextBytes {
                preview = nil
                oversizedByteCount = data.count
                metrics = nil
            } else {
                let text = String(data: data, encoding: .utf8)
                    ?? String(data: data, encoding: .utf16)
                let normalizedText = text.map(normalizedPreview) ?? ""
                preview = normalizedText.nilIfEmpty
                oversizedByteCount = nil
                metrics = await textMetrics(for: text, tokenizer: tokenizer)
            }
        case .timedOut, .cancelled, .failed, .unavailable:
            return (
                classification: unavailableClassification(generation: generation),
                metrics: nil
            )
        }
        return (
            classification: .text(
                generation: generation,
                preview: preview,
                oversizedByteCount: oversizedByteCount
            ),
            metrics: metrics
        )
    }

    private static func textMetrics(
        for text: String?,
        tokenizer: ClipboardTokenizer?
    ) async -> ClipboardTextMetrics? {
        guard let text, let tokenizer else { return nil }
        return await ClipboardTextMetrics.count(in: text, using: tokenizer)
    }

    private static func textRepresentation(
        in types: [(NSPasteboardItem, NSPasteboard.PasteboardType)]
    ) -> (NSPasteboardItem, NSPasteboard.PasteboardType)? {
        types.first(where: { _, type in type == .string }) ?? types.first(where: { _, type in
            guard let uniformType = UTType(type.rawValue) else { return false }
            return uniformType.conforms(to: .plainText) || uniformType.conforms(to: .url)
        })
    }

    private struct MaterializedText {
        let item: NSPasteboardItem
        let type: NSPasteboard.PasteboardType
        let result: PasteboardBoundedReadResult
    }

    private static func readTextPayload(
        in types: [(NSPasteboardItem, NSPasteboard.PasteboardType)],
        payloadReader: any PasteboardPayloadReading
    ) async -> MaterializedText? {
        guard !Task.isCancelled,
              let (item, type) = textRepresentation(in: types) else {
            return nil
        }
        let result = await payloadReader.readData(
            from: item,
            forType: type,
            maximumBytes: maximumFingerprintSourceBytes
        )
        guard !Task.isCancelled else { return nil }
        return MaterializedText(item: item, type: type, result: result)
    }

    private static func textFingerprint(
        from textPayload: MaterializedText?
    ) async -> ClipboardTextFingerprint? {
        guard let textPayload,
              case let .data(data) = textPayload.result,
              data.count <= maximumFingerprintSourceBytes,
              !Task.isCancelled else {
            return nil
        }
        let digest = await Task.detached(priority: .userInitiated) {
            Data(SHA256.hash(data: data))
        }.value
        guard !Task.isCancelled else { return nil }
        return ClipboardTextFingerprint(
            typeIdentifier: textPayload.type.rawValue,
            itemTypeIdentifiers: textPayload.item.types.prefix(maximumTypeEntries).map(\.rawValue).sorted(),
            byteCount: data.count,
            digest: digest
        )
    }

    private static func classifyGeneric(
        types: [(NSPasteboardItem, NSPasteboard.PasteboardType)],
        generation: UInt64
    ) -> ClipboardPayloadClassification {
        for (_, type) in types {
            guard let description = friendlyDescription(for: type) else { continue }
            return .generic(generation: generation, typeDescription: description)
        }
        return .generic(generation: generation, typeDescription: nil)
    }

    private static func boundedTypes(
        in items: [NSPasteboardItem]
    ) -> [(NSPasteboardItem, NSPasteboard.PasteboardType)] {
        var result: [(NSPasteboardItem, NSPasteboard.PasteboardType)] = []
        result.reserveCapacity(maximumTypeEntries)

        for item in items.prefix(maximumFileItems) {
            for type in item.types {
                result.append((item, type))
                if result.count == maximumTypeEntries {
                    return result
                }
            }
        }
        return result
    }

    private static func friendlyDescription(for type: NSPasteboard.PasteboardType) -> String? {
        guard let description = UTType(type.rawValue)?.localizedDescription?
            .trimmingCharacters(in: .whitespacesAndNewlines),
            !description.isEmpty,
            description != type.rawValue,
            description.count <= 80,
            description.unicodeScalars.count <= 80,
            description.allSatisfy({
                $0.unicodeScalars.count <= maximumPreviewScalarsPerCharacter
            }),
            description.unicodeScalars.allSatisfy({ !CharacterSet.controlCharacters.contains($0) })
        else {
            return nil
        }

        if !description.contains(where: \.isWhitespace),
           description.contains(where: { ".:/".contains($0) }) {
            return nil
        }

        return description.prefix(1).lowercased() + description.dropFirst()
    }

}
extension ClipboardPayloadClassifier {
    private static func scanFiles(
        in items: [NSPasteboardItem],
        generation: UInt64,
        totalItemCount: Int?,
        fileURLReader: any PasteboardFileURLReading
    ) async -> ClipboardPayloadClassification? {
        var state = FileScanState(remainingURLBytes: maximumFileURLReadBytes)

        fileScan: for item in items.prefix(maximumFileItems) {
            guard PasteboardTypePolicy.containsFileURL(
                in: item,
                maximumTypesPerItem: maximumTypeEntries
            ) else {
                continue
            }
            guard state.canRead else {
                state.markBudgetExhausted()
                break fileScan
            }

            state.fileURLReadCount += 1
            let result = await fileURLReader.readFileURLData(
                from: item,
                maximumBytes: min(PasteboardSnapshot.maximumFileURLBytes, state.remainingURLBytes),
                timeout: PasteboardSnapshot.maximumFileURLReadDuration
            )
            guard !Task.isCancelled else { return nil }

            switch result {
            case let .data(data):
                guard state.consume(data: data) else { break fileScan }
            case .missing:
                state.recordUnknown()
            case .tooLarge:
                state.markBudgetExhausted()
                break fileScan
            case .unavailable, .timedOut, .failed:
                return unavailableClassification(generation: generation)
            case .cancelled:
                return Task.isCancelled
                    ? nil
                    : unavailableClassification(generation: generation)
            }
        }

        return state.classification(
            generation: generation,
            totalItemCount: totalItemCount,
            scannedItemCount: items.count
        )
    }

    @MainActor
    private struct FileScanState {
        var firstURL: URL?
        var firstName: String?
        var fileCount = 0
        var remainingURLBytes: Int
        var fileURLReadCount = 0
        var budgetExhausted = false

        var canRead: Bool {
            fileURLReadCount < ClipboardPayloadClassifier.maximumFileURLReadCount
                && remainingURLBytes > 0
        }

        mutating func markBudgetExhausted() {
            budgetExhausted = true
            recordUnknown()
        }

        mutating func recordUnknown() {
            fileCount += 1
            if firstName == nil {
                firstName = "file"
            }
        }

        mutating func consume(data: Data) -> Bool {
            guard data.count <= remainingURLBytes else {
                markBudgetExhausted()
                return false
            }
            remainingURLBytes -= data.count

            guard let url = PasteboardTypePolicy.url(from: data) else {
                recordUnknown()
                return true
            }
            if !isLocalFileURL(url), url.scheme != nil || url.host != nil {
                return true
            }
            guard isLocalFileURL(url) else {
                recordUnknown()
                return true
            }
            fileCount += 1
            if firstName == nil {
                firstURL = url
                firstName = url.lastPathComponent.nilIfEmpty
            }
            return true
        }

        func classification(
            generation: UInt64,
            totalItemCount: Int?,
            scannedItemCount: Int
        ) -> ClipboardPayloadClassification? {
            guard fileCount > 0 else { return nil }
            let itemCount = totalItemCount ?? scannedItemCount
            let scanWasTruncated = itemCount > ClipboardPayloadClassifier.maximumFileItems
            let overflow = fileCount == ClipboardPayloadClassifier.maximumFileItems && scanWasTruncated
            let imageEnrichment = firstURL.flatMap { url -> ClipboardImageEnrichmentRequest? in
                guard let type = PasteboardTypePolicy.imageType(for: url) else { return nil }
                return ClipboardImageEnrichmentRequest(
                    generation: generation,
                    localFileURL: url,
                    typeIdentifier: type.identifier
                )
            }
            return .files(
                generation: generation,
                firstName: firstName ?? "file",
                count: fileCount,
                overflow: overflow,
                uncertain: budgetExhausted || scanWasTruncated,
                representativeFileURL: firstURL,
                imageEnrichment: imageEnrichment
            )
        }
    }
}
